/**
 * Filter locations by region key
 */
export function getLocationsByRegion(regionId: string): LocationData[] {
  if (regionId === 'all') {
    return WORLD_LOCATIONS_DATA;
  }
  return WORLD_LOCATIONS_DATA.filter((l) => l.region === regionId);
}

/**
 * Search locations by query string (searches Nepali name, English name, Country, District, State)
 */
export function searchWorldLocations(query: string, regionId: string = 'all'): LocationData[] {
  const q = query.trim().toLowerCase();
  const pool = getLocationsByRegion(regionId);
  if (!q) return pool;

  return pool.filter((loc) => {
    return (
      loc.name.toLowerCase().includes(q) ||
      (loc.englishName && loc.englishName.toLowerCase().includes(q)) ||
      loc.country.toLowerCase().includes(q) ||
      (loc.district && loc.district.toLowerCase().includes(q)) ||
      (loc.state && loc.state.toLowerCase().includes(q)) ||
      (loc.province && loc.province.toLowerCase().includes(q))
    );
  });
}

/**
 * Helper to calculate time difference between a given timezone and Nepal Standard Time (UTC+5:45 = +5.75)
 */
export function formatTimeDifferenceFromNepal(tz: number): string {
  const diffHours = tz - 5.75;
  if (Math.abs(diffHours) < 0.05) {
    return 'नेपाल समय समान (NPT UTC+5:45)';
  }

  const sign = diffHours > 0 ? 'अगाडि' : 'पछाडि';
  const absDiff = Math.abs(diffHours);
  const h = Math.floor(absDiff);
  const m = Math.round((absDiff - h) * 60);

  const parts = [];
  if (h > 0) parts.push(`${toDevanagariNumerals(h)} घण्टा`);
  if (m > 0) parts.push(`${toDevanagariNumerals(m)} मिनेट`);

  return `नेपाल समयभन्दा ${parts.join(' ')} ${sign}`;
}

/**
 * Format Timezone string e.g. UTC+5:45 or UTC-5:00
 */
export function formatTimeZoneString(tz: number): string {
  const sign = tz >= 0 ? '+' : '-';
  const abs = Math.abs(tz);
  const h = Math.floor(abs);
  const m = Math.round((abs - h) * 60);
  const mStr = m === 0 ? '00' : m < 10 ? `0${m}` : `${m}`;
  return `UTC${sign}${h}:${mStr}`;
}

/**
 * Format coordinates nicely into Devanagari DMS / decimal
 */
export function formatCoordinatesDevanagari(lat: number, lon: number): string {
  const latDir = lat >= 0 ? 'उ' : 'द'; // उत्तर / दक्षिण
  const lonDir = lon >= 0 ? 'पू' : 'प'; // पूर्व / पश्चिम
  const latStr = `${toDevanagariNumerals(Math.abs(lat).toFixed(2))}° ${latDir}`;
  const lonStr = `${toDevanagariNumerals(Math.abs(lon).toFixed(2))}° ${lonDir}`;
  return `${latStr}, ${lonStr}`;
}
