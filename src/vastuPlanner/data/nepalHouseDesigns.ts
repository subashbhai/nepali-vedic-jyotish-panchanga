// Helper to quickly build standard rooms
const createRoom = (
  id: string,
  category: RoomCategory,
  nameNepali: string,
  floorNumber: number,
  preferredDirection: CompassDirection,
  minLength: number,
  minWidth: number,
  doorCount = 1,
  windowCount = 1,
  plumbing = false,
  appliances: string[] = []
): PlannedRoom => ({
  id,
  category,
  nameNepali,
  preferredDirection,
  floorNumber,
  minLength,
  minWidth,
  doorCount,
  doorType: category === 'toilet' || category === 'bathroom' ? 'D3' : floorNumber === 0 && category === 'living' ? 'D1' : 'D2',
  windowCount,
  windowType: category === 'toilet' ? 'V1' : 'W1',
  hasChhajja: true,
  hasPlumbing: plumbing,
  plumbingFixtures: plumbing ? (category === 'kitchen' ? ['sink', 'tap', 'ro'] : ['commode', 'shower', 'basin', 'geyser']) : undefined,
  lightPointsCount: 2,
  fanPointsCount: 1,
  powerSocketsCount: category === 'kitchen' ? 3 : 2,
  appliances,
  priority: 'high'
});

