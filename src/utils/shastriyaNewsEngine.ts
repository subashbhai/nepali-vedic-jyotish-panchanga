// HELPER: Map Tithi Name String to Tithi Number (1 to 15)
// ============================================================================
export function mapTithiNameToNumber(tithiStr: string): number {
  if (!tithiStr) return 1;
  const clean = tithiStr.toLowerCase();

  if (clean.includes('प्रतिपदा') || clean.includes('pratipada') || clean.includes('padwa')) return 1;
  if (clean.includes('द्वितीया') || clean.includes('dwitiya') || clean.includes('dwitiya')) return 2;
  if (clean.includes('तृतीया') || clean.includes('tritiya') || clean.includes('teej')) return 3;
  if (clean.includes('चतुर्थी') || clean.includes('chaturthi') || clean.includes('chauth')) return 4;
  if (clean.includes('पञ्चमी') || clean.includes('panchami')) return 5;
  if (clean.includes('षष्ठी') || clean.includes('shashthi') || clean.includes('chhat')) return 6;
  if (clean.includes('सप्तमी') || clean.includes('saptami')) return 7;
  if (clean.includes('अष्टमी') || clean.includes('ashtami')) return 8;
  if (clean.includes('नवमी') || clean.includes('navami')) return 9;
  if (clean.includes('दशमी') || clean.includes('dashami')) return 10;
  if (clean.includes('एकादशी') || clean.includes('ekadashi')) return 11;
  if (clean.includes('द्वादशी') || clean.includes('dwadashi')) return 12;
  if (clean.includes('त्रयोदशी') || clean.includes('trayodashi') || clean.includes('terash')) return 13;
  if (clean.includes('चतुर्दशी') || clean.includes('chaturdashi')) return 14;
  if (clean.includes('पूर्णिमा') || clean.includes('purnima') || clean.includes('punhi') || clean.includes('औंसी') || clean.includes('औँसी') || clean.includes('amavasya')) return 15;

  return 1;
}

