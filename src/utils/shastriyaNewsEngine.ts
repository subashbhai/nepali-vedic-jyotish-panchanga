// Helper function to map tithi name to number 1-15
export function mapTithiNameToNumber(tName: string): number {
  if (!tName) return 1;
  const clean = tName.trim();
  if (clean.includes('प्रतिपदा') || clean.includes('पड्वा')) return 1;
  if (clean.includes('द्वितीया') || clean.includes('दुतिया')) return 2;
  if (clean.includes('तृतीया') || clean.includes('तृतीया')) return 3;
  if (clean.includes('चतुर्थी') || clean.includes('चौथी')) return 4;
  if (clean.includes('पञ्चमी') || clean.includes('पञ्चमी')) return 5;
  if (clean.includes('षष्ठी') || clean.includes('छठी')) return 6;
  if (clean.includes('सप्तमी')) return 7;
  if (clean.includes('अष्टमी')) return 8;
  if (clean.includes('नवमी')) return 9;
  if (clean.includes('दशमी')) return 10;
  if (clean.includes('एकादशी')) return 11;
  if (clean.includes('द्वादशी')) return 12;
  if (clean.includes('त्रयोदशी') || clean.includes('तेरस')) return 13;
  if (clean.includes('चतुर्दशी') || clean.includes('चौदस')) return 14;
  if (clean.includes('पूर्णिमा') || clean.includes('पुन्ही') || clean.includes('औंसी') || clean.includes('अमावस्या')) return 15;
  return 1;
}

