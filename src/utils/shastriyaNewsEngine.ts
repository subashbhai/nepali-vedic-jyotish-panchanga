// ============================================================================
// 3. AUTO LIFECYCLE SYNC ENGINE: REAL-TIME DAYS CALCULATION & MIDNIGHT PRUNING
// ============================================================================
export function syncAndPruneShastriyaNews(
  existingArticles: SamacharArticle[],
  todayBS?: string,
  todayAD?: string,
  todayTithiName: string = 'प्रतिपदा',
  todayPaksha: 'शुक्ल' | 'कृष्ण' = 'शुक्ल'
): SamacharArticle[] {
  // 1. Resolve Active Today AD & BS Dates accurately
  const activeTodayAD = todayAD || new Date().toISOString().split('T')[0];
  let activeTodayBS = todayBS;
  if (!activeTodayBS) {
    const converted = convertADToBS(activeTodayAD);
    activeTodayBS = converted.formattedBS;
  }

  // Parse current BS Date: e.g. "२०८३-०६-१८"
  const bsParts = activeTodayBS.replace(/[०-९]/g, (d) => '०१२३४५६७८९'.indexOf(d).toString()).split('-');
  const currentBSYear = parseInt(bsParts[0], 10) || 2083;

  // 2. Filter out EXPIRED daily tithi articles and past festivals, and sanitize any legacy Unsplash images
  let updatedArticles = existingArticles.map((art) => {
    // If it contains unsplash or broken external image, replace with proper local asset
    if (art.coverImageUrl && art.coverImageUrl.includes('images.unsplash.com')) {
      if (art.id.startsWith('daily_tithi_article_')) {
        const tNum = mapTithiNameToNumber(todayTithiName);
        const tData = SHASTRIYA_TITHI_DATABASE[tNum] || SHASTRIYA_TITHI_DATABASE[1];
        return { ...art, coverImageUrl: tData.coverImageUrl };
      }
      if (art.id.startsWith('auto_festival_')) {
        const fCode = art.id.replace('auto_festival_', '').replace('_2083', '');
        const match = MAJOR_FESTIVALS_SPEC.find(f => f.code === fCode);
        if (match) return { ...art, coverImageUrl: match.coverImageUrl };
      }
      if (art.id.startsWith('graha_news_')) {
        return { ...art, coverImageUrl: '/assets/festivals/tihar_deepawali.jpg' };
      }
    }
    return art;
  }).filter((art) => {
    // If it's a daily tithi auto-article and its date is NOT today's date, auto-delete it at midnight!
    if (art.id.startsWith('daily_tithi_article_')) {
      return art.publishedAtBS === activeTodayBS;
    }
    return true;
  });

  // 3. Ensure TODAY's running Tithi article exists and has the accurate deity image and rich content
  const todayTithiArticleId = `daily_tithi_article_${activeTodayBS.replace(/[^0-9]/g, '_')}`;
  const tithiIdx = updatedArticles.findIndex((a) => a.id === todayTithiArticleId);
  const freshTithiArticle = generateTodayTithiShastriyaArticle(todayTithiName, todayPaksha, activeTodayBS, activeTodayAD);

  if (tithiIdx >= 0) {
    // Refresh today's article to guarantee fresh title and local deity image!
    updatedArticles[tithiIdx] = {
      ...updatedArticles[tithiIdx],
      title: freshTithiArticle.title,
      summary: freshTithiArticle.summary,
      content: freshTithiArticle.content,
      coverImageUrl: freshTithiArticle.coverImageUrl
    };
  } else {
    // Insert new tithi article at the top of the list
    updatedArticles.unshift(freshTithiArticle);
  }

  // 4. Scan for Upcoming Major Festivals within 1 Month (30 Days) window using REAL calendar day differences
  const activeADDate = new Date(activeTodayAD);

  MAJOR_FESTIVALS_SPEC.forEach((fSpec) => {
    // Calculate exact Gregorian date of this festival in BS Year 2083
    let festADStr: string;
    try {
      festADStr = convertBSToAD(currentBSYear, fSpec.approxMonthBS, fSpec.approxDayBS);
    } catch {
      festADStr = '';
    }

    if (!festADStr) return;

    const festADDate = new Date(festADStr);
    const diffMs = festADDate.getTime() - activeADDate.getTime();
    const exactDaysRemaining = Math.round(diffMs / (1000 * 60 * 60 * 24));

    const festivalArticleId = `auto_festival_${fSpec.code}_2083`;
    const existingIdx = updatedArticles.findIndex((a) => a.id === festivalArticleId);

    // If festival is within 30 days ahead (0 to 30 days) or happening today / tomorrow
    if (exactDaysRemaining >= -1 && exactDaysRemaining <= 30) {
      const festDateBS = `२०८३-${String(fSpec.approxMonthBS).padStart(2, '०')}-${String(fSpec.approxDayBS).padStart(2, '०')}`;
      const daysText = exactDaysRemaining === 0 ? 'आज' : exactDaysRemaining === 1 ? 'भोलि' : `${toDevanagariNumerals(exactDaysRemaining)} दिन बाँकी`;

      const shlokasText = fSpec.shlokas
        .map(
          (s, i) => `
### 📜 शास्त्रीय श्लोक प्रमाण #${i + 1} (${s.source}):
> **"${s.sanskrit}"**
> 
> **नेपाली भावार्थ:** ${s.meaning}
`
        )
        .join('\n');

      const mantrasText = fSpec.mantras
        .map(
          (m) => `
- **${m.title}:** \`${m.mantra}\`  
  *(फल: ${m.benefit})*
`
        )
        .join('\n');

      const fullFestivalContent = `# ${fSpec.title}

**पर्व मिति:** वि.सं. ${festDateBS} (${daysText})  
**धार्मिक अनुष्ठान:** ${fSpec.festivalName}  
**शुभ साइत विवरण:** ${fSpec.exactSaitDetails}  
**शास्त्रीय संकलन:** बालानन्द वैदिक पञ्चाङ्ग अनुसन्धान केन्द्र

---

## १. किन मनाइन्छ यो पर्व ? (धार्मिक तथा ऐतिहासिक पृष्ठभूमि)
${fSpec.whyCelebrated}

---

## २. धार्मिक, सांस्कृतिक तथा आध्यात्मिक महत्त्व
${fSpec.spiritualMahatmya}

${shlokasText}

---

## ३. यकिन शुभ साइत तथा समय तालिका
${fSpec.exactSaitDetails}

### 🪔 दैनिक जप तथा कल्याणकारी मन्त्रहरू:
${mantrasText}

---

## ४. विस्तृत पौराणिक मान्यता तथा आख्यान (कथा)
${fSpec.katha}

---

## ५. पूजन विधि, नियम तथा आवश्यक सामग्रीहरू
${fSpec.vidhiAndSamagri}

---

*स्रोत: नेपाल पञ्चाङ्ग निर्णायक विकास समिति तथा निर्णयसिन्धु।*
`;

      const festArticle: SamacharArticle = {
        id: festivalArticleId,
        slug: `festival-${fSpec.code}`,
        title: fSpec.title, // Clean news headline! (No bracketed prefix in title)
        summary: fSpec.summary,
        content: fullFestivalContent,
        category: 'festival',
        categoryNameNepali: 'चाडपर्व तथा मेला',
        author: 'बालानन्द संस्कृति तथा चाडपर्व अनुसन्धान परिषद',
        authorRole: 'वरिष्ठ संस्कृतिविद्',
        coverImageUrl: fSpec.coverImageUrl,
        publishedAtBS: festDateBS,
        publishedAtAD: activeTodayAD,
        isPublished: true,
        isFeatured: exactDaysRemaining <= 7, // Highlight as featured if within 7 days
        isBreaking: exactDaysRemaining <= 1, // Breaking ticker if today/tomorrow
        tags: fSpec.tags,
        viewsCount: 2800 + Math.floor(Math.random() * 500),
        readTimeMinutes: 6,
        source: 'नेपाल पञ्चाङ्ग निर्णायक विकास समिति'
      };

      if (existingIdx >= 0) {
        // Dynamically update existing festival article with the clean title and fresh content!
        updatedArticles[existingIdx] = {
          ...updatedArticles[existingIdx],
          title: fSpec.title,
          summary: fSpec.summary,
          content: fullFestivalContent,
          coverImageUrl: fSpec.coverImageUrl,
          isFeatured: exactDaysRemaining <= 7,
          isBreaking: exactDaysRemaining <= 1
        };
      } else {
        // Insert new festival article into the list
        updatedArticles.push(festArticle);
      }
    } else {
      // If festival is already past (e.g. Teej was last month), prune it out automatically!
      if (existingIdx >= 0) {
        updatedArticles.splice(existingIdx, 1);
      }
    }
  });

  return updatedArticles;
}
