// ============================================================================
// 3. AUTO LIFECYCLE SYNC ENGINE: MIDNIGHT ROLLOVER & 1-MONTH ADVANCE SCAN
// ============================================================================
export function syncAndPruneShastriyaNews(
  existingArticles: SamacharArticle[],
  todayBS: string,
  todayAD: string,
  todayTithiName: string = 'प्रतिपदा',
  todayPaksha: 'शुक्ल' | 'कृष्ण' = 'शुक्ल'
): SamacharArticle[] {
  // Parse current BS Date: e.g. "२०८३-०५-२५"
  const bsParts = todayBS.replace(/[०-९]/g, (d) => '०१२३४५६७८९'.indexOf(d).toString()).split('-');
  const currentBSYear = parseInt(bsParts[0], 10) || 2083;
  const currentBSMonth = parseInt(bsParts[1], 10) || 5;
  const currentBSDay = parseInt(bsParts[2], 10) || 25;

  const currentTotalDays = currentBSMonth * 30 + currentBSDay;

  // 1. Filter out EXPIRED daily tithi articles from past days
  // (Daily tithi articles expire at 12:00 AM midnight when todayBS advances)
  let updatedArticles = existingArticles.filter((art) => {
    // If it's a daily tithi auto-article and its date is older than todayBS, auto-delete it!
    if (art.id.startsWith('daily_tithi_article_')) {
      return art.publishedAtBS === todayBS;
    }
    // If it's an auto-festival article that has completely passed (more than 2 days ago), auto-prune it!
    if (art.id.startsWith('auto_festival_')) {
      const artBsParts = art.publishedAtBS.replace(/[०-९]/g, (d) => '०१२३४५६७८९'.indexOf(d).toString()).split('-');
      const artMonth = parseInt(artBsParts[1], 10) || currentBSMonth;
      const artDay = parseInt(artBsParts[2], 10) || currentBSDay;
      const artTotalDays = artMonth * 30 + artDay;

      // If festival ended more than 1 day ago, prune it
      if (currentTotalDays - artTotalDays > 1) {
        return false;
      }
    }
    return true;
  });

  // 2. Ensure TODAY's running Tithi article exists and is fresh
  const todayTithiArticleId = `daily_tithi_article_${todayBS.replace(/[^0-9]/g, '_')}`;
  const hasTodayTithi = updatedArticles.some((a) => a.id === todayTithiArticleId);

  if (!hasTodayTithi) {
    const newTithiArticle = generateTodayTithiShastriyaArticle(todayTithiName, todayPaksha, todayBS, todayAD);
    // Put at top of list
    updatedArticles.unshift(newTithiArticle);
  }

  // 3. Scan for Upcoming Major Festivals within 1 Month (30 Days) window
  MAJOR_FESTIVALS_SPEC.forEach((fSpec) => {
    const fTotalDays = fSpec.approxMonthBS * 30 + fSpec.approxDayBS;
    const daysRemaining = fTotalDays - currentTotalDays;

    // If festival is within 30 days ahead (or happening today / tomorrow)
    if (daysRemaining >= -1 && daysRemaining <= 30) {
      const festivalArticleId = `auto_festival_${fSpec.code}_2083`;
      const alreadyExists = updatedArticles.some((a) => a.id === festivalArticleId);

      if (!alreadyExists) {
        const festDateBS = `२०८३-${String(fSpec.approxMonthBS).padStart(2, '०')}-${String(fSpec.approxDayBS).padStart(2, '०')}`;
        const daysText = daysRemaining === 0 ? 'आज' : daysRemaining === 1 ? 'भोलि' : `${toDevanagariNumerals(daysRemaining)} दिन बाँकी`;

        const shlokasText = fSpec.shlokas
          .map(
            (s, i) => `
### 📜 शास्त्रीय श्लोक #${i + 1} (${s.source}):
> **"${s.sanskrit}"**
> 
> **नेपाली भावार्थ:** ${s.meaning}
`
          )
          .join('\n');

        const mantrasText = fSpec.mantras
          .map(
            (m) => `
- **${m.title}:** \`${m.mantra}\`  
  *(फल: ${m.benefit})*
`
          )
          .join('\n');

        const fullFestivalContent = `# ${fSpec.title}

**पर्व मिति:** वि.सं. ${festDateBS} (${daysText})  
**धार्मिक अनुष्ठान:** ${fSpec.festivalName}  
**शास्त्रीय संकलन:** बालानन्द वैदिक पञ्चाङ्ग अनुसन्धान केन्द्र

---

## १. पर्वको शास्त्रीय महत्त्व तथा महिमा
${fSpec.summary}

${shlokasText}

---

## २. वैदिक मन्त्र तथा पूजा स्तोत्र
${mantrasText}

---

## ३. पूजा विधि, नियम तथा शुभ साइत
${fSpec.vidhiAndSait}

---

## ४. विस्तृत पौराणिक कथा तथा इतिहास
${fSpec.katha}

---

*स्रोत: नेपाल पञ्चाङ्ग निर्णायक विकास समिति तथा निर्णयसिन्धु।*
`;

        const festArticle: SamacharArticle = {
          id: festivalArticleId,
          slug: `festival-${fSpec.code}`,
          title: `[चाडपर्व विशेष - ${daysText}] ${fSpec.title}`,
          summary: fSpec.summary,
          content: fullFestivalContent,
          category: 'festival',
          categoryNameNepali: 'चाडपर्व तथा मेला',
          author: 'बालानन्द संस्कृति तथा चाडपर्व अनुसन्धान परिषद',
          authorRole: 'वरिष्ठ संस्कृतिविद्',
          coverImageUrl: fSpec.coverImageUrl,
          publishedAtBS: festDateBS,
          publishedAtAD: todayAD,
          isPublished: true,
          isFeatured: daysRemaining <= 7, // Highlight as featured if within 7 days
          isBreaking: daysRemaining <= 1, // Breaking ticker if today/tomorrow
          tags: fSpec.tags,
          viewsCount: 2800 + Math.floor(Math.random() * 500),
          readTimeMinutes: 6,
          source: 'नेपाल पञ्चाङ्ग निर्णायक विकास समिति'
        };

        updatedArticles.push(festArticle);
      }
    }
  });

  return updatedArticles;
}
