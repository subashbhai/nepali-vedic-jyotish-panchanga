export function getBPHSYogaShloka(yogaIdentifier: string): BPHSYogaShloka | undefined {
  // Check exact key match
  if (BPHS_YOGA_SHLOKAS[yogaIdentifier]) {
    return BPHS_YOGA_SHLOKAS[yogaIdentifier];
  }

  // Normalize string search
  const query = yogaIdentifier.toLowerCase().replace(/[^a-z0-9]/g, '');
  for (const [key, val] of Object.entries(BPHS_YOGA_SHLOKAS)) {
    const kNorm = key.toLowerCase().replace(/[^a-z0-9]/g, '');
    if (query.includes(kNorm) || kNorm.includes(query) || yogaIdentifier.includes(val.nameNepali) || val.nameNepali.includes(yogaIdentifier)) {
      return val;
    }
  }

  // Fallback to Gajakesari or Rajayoga
  if (yogaIdentifier.includes('गजकेसरी') || yogaIdentifier.includes('Gaja')) return BPHS_YOGA_SHLOKAS['GAJAKESARI'];
  if (yogaIdentifier.includes('बुधादित्य') || yogaIdentifier.includes('Budhaditya')) return BPHS_YOGA_SHLOKAS['BUDHADITYA'];
  if (yogaIdentifier.includes('महापुरुष') || yogaIdentifier.includes('रुचक') || yogaIdentifier.includes('भद्र') || yogaIdentifier.includes('हंस') || yogaIdentifier.includes('मालव्य') || yogaIdentifier.includes('शश')) return BPHS_YOGA_SHLOKAS['PANCHA_MAHAPURUSHA'];
  if (yogaIdentifier.includes('विपरीत') || yogaIdentifier.includes('हर्ष') || yogaIdentifier.includes('सरल') || yogaIdentifier.includes('विमल')) return BPHS_YOGA_SHLOKAS['VIPAREETA_RAJAYOGA'];
  if (yogaIdentifier.includes('नीचभङ्ग') || yogaIdentifier.includes('नीच')) return BPHS_YOGA_SHLOKAS['NEECHA_BHANGA_RAJAYOGA'];
  if (yogaIdentifier.includes('राजयोग') || yogaIdentifier.includes('धर्मकर्माधिपति')) return BPHS_YOGA_SHLOKAS['RAJAYOGA_KENDRA_TRIKONA'];

  return undefined;
}

